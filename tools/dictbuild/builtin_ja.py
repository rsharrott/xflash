def level_japanese(level_key, name, count, n_chunks):
    """(ja_name, ja_description) for one vocabulary-level set.

    `name` is the English set name.  The caller already chose this row by tag id.
    """
    level = LEVEL_JA[level_key]
    base = level['name']
    blurb = level['blurb']
    if name.endswith(' Full Set'):
        ja_name = base + '全部'
        ja_desc = '%s  このレベルの%d枚（01〜%02dのセットをまとめたもの）です。' % (
            blurb, count, n_chunks)
        return ja_name, ja_desc
    index = name.rsplit(' ', 1)[-1]
    ja_name = base + index
    ja_desc = '%s  %s／%02dセットです。' % (blurb, index, n_chunks)
    return ja_name, ja_desc


def chunk_japanese(base_en, name, count, n_chunks, width):
    """(ja_name, ja_description) for a numbered cut or its Full Set."""
    spec = CHUNK_JA[base_en]
    base = spec['name']
    blurb = spec['blurb']
    if name.endswith(' Full Set'):
        ja_name = base + '全部'
        ja_desc = '%s  このリストの%d枚（%s〜%sのセットをまとめたもの）です。' % (
            blurb, count, _pad(1, width), _pad(n_chunks, width))
        return ja_name, ja_desc
    index = name.rsplit(' ', 1)[-1]
    ja_name = base + index
    ja_desc = '%s  %dセット中の%sです。' % (blurb, n_chunks, index)
    return ja_name, ja_desc


def _pad(number, width):
    return '%0*d' % (width, number)
