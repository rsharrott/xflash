data class StudyColors(
    val card: Color,
    val headword: Color,
    val reading: Color,
    val romaji: Color,
    val meaning: Color,
    val showAnswer: Color,
    val onShowAnswer: Color,
    val wrongFill: Color,
    val wrongLabel: Color,
    val wrongOutline: Color,
    val wrongBadge: Color,
    val onWrongBadge: Color,
    val rightFill: Color,
    val rightLabel: Color,
    val rightBadge: Color,
    val onRightBadge: Color,
    val bar: Color,
    val track: Color,
    val toggleFill: Color,
    val toggleLabel: Color,
    val posFill: Color,
    val posInk: Color,
    val texture: CardTexture,
    val listSupporting: Color,
    val screenSecondary: Color,
)

fun studyColors(theme: StudyTheme, dark: Boolean): StudyColors {
    if (dark) return darkPaper()
    return when (theme) {
        StudyTheme.PAPER -> paper()
        StudyTheme.FIRE -> fire()
        StudyTheme.WATER -> water()
        StudyTheme.KIMONO -> kimono()
        StudyTheme.KUTANI -> kutani()
    }
}

